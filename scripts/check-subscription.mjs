import fs from 'node:fs';
import crypto from 'node:crypto';
import JSON5 from 'json5';
const file=process.argv[2]??'dist/gkd-fused.json5';
const manifestPath=process.argv[3]??'dist/gkd-fused-manifest.json';
const versionPath=process.argv[4]??'dist/gkd-fused.version.json';
const bytes=fs.readFileSync(file);
if(bytes.length<1000)throw Error('Subscription unexpectedly empty or tiny');
const subscription=JSON5.parse(bytes.toString('utf8'));
const manifest=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
const version=JSON.parse(fs.readFileSync(versionPath,'utf8'));
const fail=message=>{throw Error(message)};
if(!Number.isSafeInteger(subscription.id)||!Number.isSafeInteger(subscription.version)||subscription.version<1)fail('Invalid subscription identity/version');
if(subscription.id!==manifest.id||subscription.version!==manifest.version)fail('Subscription and fusion manifest identity/version mismatch');
if(version.id!==subscription.id||version.version!==subscription.version)fail('Fusion version file does not match subscription identity/version');
if(subscription.checkUpdateUrl!=='./gkd-fused.version.json')fail('Subscription checkUpdateUrl must target ./gkd-fused.version.json');
if(!Array.isArray(subscription.apps)||!subscription.apps.length)fail('Missing apps');
if(!Array.isArray(subscription.globalGroups))fail('Missing globalGroups');
const appGroups=subscription.apps.reduce((n,app)=>{if(typeof app.id!=='string'||!Array.isArray(app.groups))fail('Malformed app');return n+app.groups.length},0);
const groups=appGroups+subscription.globalGroups.length;
const rules=[...subscription.globalGroups,...subscription.apps.flatMap(a=>a.groups)].reduce((n,g)=>n+(Array.isArray(g.rules)?g.rules.length:0),0);
const sha256=crypto.createHash('sha256').update(bytes).digest('hex');
if(sha256!==manifest.subscriptionSha256)fail('Fusion manifest SHA-256 mismatch');
for(const [field,actual] of Object.entries({apps:subscription.apps.length,appGroups,globalGroups:subscription.globalGroups.length,groups,rules}))if(manifest.counts?.[field]!==actual)fail('Fusion manifest count mismatch: '+field);
console.log(JSON.stringify({file,versionPath,bytes:bytes.length,sha256,id:subscription.id,version:subscription.version,apps:subscription.apps.length,appGroups,globalGroups:subscription.globalGroups.length,groups,rules,checkUpdateUrl:subscription.checkUpdateUrl},null,2));
